package projectioncompiler

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"
	"strconv"
	"strings"

	"google.golang.org/protobuf/encoding/protojson"
)

// GenerateTypeScript emits a framework-independent module and a separate React
// entry point. Mutation schemas/code generation never enter this pipeline.
func GenerateTypeScript(operations []Operation, runtimeImport, moduleImport string) ([]byte, []byte, error) {
	var core, react bytes.Buffer
	fmt.Fprintln(&core, "// Code generated by weave projectiongen. DO NOT EDIT.")
	// GraphQL identifiers cannot contain '$'. Keep implementation imports in a
	// disjoint namespace rather than banning otherwise valid operation names.
	fmt.Fprintf(&core, "import * as $runtime from %s\n\n", strconv.Quote(runtimeImport))
	fmt.Fprintln(&react, "// Code generated by weave projectiongen. DO NOT EDIT.")
	fmt.Fprintf(&react, "import { useTypedProjection as $useTypedProjection } from %s\n", strconv.Quote(runtimeImport+"/react"))
	fmt.Fprintf(&react, "import type { ReactiveClient as $ReactiveClient, ProjectionOptions as $ProjectionOptions } from %s\n", strconv.Quote(runtimeImport))
	fmt.Fprintf(&react, "import * as $projections from %s\n", strconv.Quote(moduleImport))
	symbols := map[string]bool{}
	for _, operation := range operations {
		for _, symbol := range []string{operation.Name, operation.Name + "Parameters", operation.Name + "Data"} {
			if symbols[symbol] || reservedTS[symbol] {
				return nil, nil, fmt.Errorf("generated TypeScript identifier collision/reserved name: %s", symbol)
			}
			symbols[symbol] = true
		}
		root, err := protojson.Marshal(operation.Root)
		if err != nil {
			return nil, nil, err
		}
		// protojson intentionally makes no stable-whitespace guarantee. Normalize
		// it before emitting checked-in code so independent runs agree bytewise.
		var compact bytes.Buffer
		if err := json.Compact(&compact, root); err != nil {
			return nil, nil, err
		}
		root = compact.Bytes()
		shape, err := json.MarshalIndent(operation.Shape, "", "  ")
		if err != nil {
			return nil, nil, err
		}
		parameters, err := json.Marshal(operation.Parameters)
		if err != nil {
			return nil, nil, err
		}
		if operation.Parameters == nil {
			parameters = []byte("[]")
		}
		fmt.Fprintf(&core, "export interface %sParameters {\n", operation.Name)
		for _, parameter := range operation.Parameters {
			fmt.Fprintf(&core, "  readonly %s: %s\n", strconv.Quote(parameter.Name), tsType(parameter.Type))
		}
		fmt.Fprintf(&core, "}\nexport type %sData = %s\n\n", operation.Name, tsNode(operation.Shape))
		fmt.Fprintf(&core, "export const %s = $runtime.defineProjection<%sParameters, %sData>(\n  %s,\n  %s,\n  %s,\n)\n\n", operation.Name, operation.Name, operation.Name, root, shape, parameters)
		fmt.Fprintf(&react, "export function use%s(client: $ReactiveClient, parameters: $projections.%sParameters, options?: $ProjectionOptions) {\n  return $useTypedProjection(client, $projections.%s, parameters, options)\n}\n", operation.Name, operation.Name, operation.Name)
	}
	return core.Bytes(), react.Bytes(), nil
}

var reservedTS = map[string]bool{
	"arguments": true, "eval": true, // Forbidden bindings in strict-mode modules.
	// ECMAScript keywords, including module/strict-mode reserved words.
	"await": true, "break": true, "case": true, "catch": true, "class": true,
	"const": true, "continue": true, "debugger": true, "default": true, "delete": true,
	"do": true, "else": true, "enum": true, "export": true, "extends": true,
	"false": true, "finally": true, "for": true, "function": true, "if": true,
	"import": true, "in": true, "instanceof": true, "new": true, "null": true,
	"return": true, "super": true, "switch": true, "this": true, "throw": true,
	"true": true, "try": true, "typeof": true, "var": true, "void": true,
	"while": true, "with": true, "yield": true,
	"implements": true, "interface": true, "let": true, "package": true,
	"private": true, "protected": true, "public": true, "static": true,
}

func tsNode(shape *Shape) string {
	var stored, computed []Field
	for _, field := range shape.Fields {
		if field.Computed {
			computed = append(computed, field)
		} else {
			stored = append(stored, field)
		}
	}
	row := "$runtime.ProjectionFields<" + tsObject(stored, shape.Children) + ", " + tsObject(computed, nil) + ">"
	if shape.Kind == "list" {
		return "$runtime.ProjectedList<" + row + ">"
	}
	return "$runtime.ProjectedEntity<" + row + ">"
}
func tsObject(fields []Field, children map[string]*Shape) string {
	var parts []string
	for _, field := range fields {
		parts = append(parts, "readonly "+strconv.Quote(field.Name)+": "+tsType(field.Type))
	}
	var names []string
	for name := range children {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		parts = append(parts, "readonly "+strconv.Quote(name)+": "+tsNode(children[name])+" | undefined")
	}
	return "{ " + strings.Join(parts, "; ") + " }"
}
func tsType(typ Type) string {
	value := "string"
	switch typ.Kind {
	case "bool":
		value = "boolean"
	case "integer":
		value = "bigint"
	case "int32", "float", "finiteFloat":
		value = "number"
	case "structured":
		value = "$runtime.Value"
	case "list":
		value = "ReadonlyArray<" + tsType(*typ.Element) + ">"
	case "object":
		value = tsObject(typ.Fields, nil)
	}
	if typ.Nullable {
		value += " | null | undefined"
	}
	return value
}
